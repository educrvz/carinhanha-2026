function parseDmsCoordinate(value) {
  const match = value.match(/(\d+)°(\d+)'([\d.]+)"([NS])\s+(\d+)°(\d+)'([\d.]+)"([EW])/);
  if (!match) throw new Error(`Coordenada inválida: ${value}`);
  const latitude = Number(match[1]) + Number(match[2]) / 60 + Number(match[3]) / 3600;
  const longitude = Number(match[5]) + Number(match[6]) / 60 + Number(match[7]) / 3600;
  return {
    lat: match[4] === 'S' ? -latitude : latitude,
    lon: match[8] === 'W' ? -longitude : longitude
  };
}

